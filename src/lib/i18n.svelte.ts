// German and English. The choice lives in Settings (General → Language): System follows the
// browser's languages, Deutsch or English pins one. Skibbo speaks German first, whatever the browser
// says, like Stichle, Stammtisch and Würfle: its players are the German-speaking afternoon meeting.
// So with nothing saved it's Deutsch, and System is saved as the word 'system' under `ewo:lang` (the
// family's key). public/boot.js applies it before first paint. From Würfle's i18n.svelte.ts.
//
// The game's words: your own pile is the stock (Vorrat), the four in the middle are the piles
// (Stapel), yours to end a turn on are the discard piles (Ablage), the wild card is the Joker. The
// game's trademarked name never appears.

export type Lang = 'de' | 'en';
export type LangChoice = Lang | 'system';

const KEY = 'ewo:lang';
const DEFAULT: LangChoice = 'de';

function storedChoice(): LangChoice {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === 'en' || stored === 'de' || stored === 'system') return stored;
  } catch {
    // storage blocked: the default
  }
  return DEFAULT;
}

/** The first of the browser's languages the game speaks, English otherwise (as public/boot.js). */
export function systemLang(): Lang {
  for (const tag of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const base = tag?.toLowerCase().slice(0, 2);
    if (base === 'de' || base === 'en') return base;
  }
  return 'en';
}

const choice = storedChoice();
export const i18n = $state({ choice, lang: choice === 'system' ? systemLang() : choice });

/** Stores a choice and shows the page in that language. */
export function setLanguage(next: LangChoice) {
  i18n.choice = next;
  i18n.lang = next === 'system' ? systemLang() : next;
  document.documentElement.lang = i18n.lang;
  try {
    localStorage.setItem(KEY, next);
  } catch {
    // not kept
  }
}

